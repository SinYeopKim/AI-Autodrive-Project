# [1단계 전용] 가변저항 연동 비전 차선 유지 주행 마스터 코드 (S자 완전 정복판)
import Function_Library as fl  # 주최측 하드웨어 제어 라이브러리
import cv2  # 영상 처리를 위한 OpenCV 라이브러리

# ==============================================================================
# [1] 시스템 기본 설정 파라미터
# ==============================================================================
# 카메라 화면(가로 640)을 기준으로 차체가 트랙의 정중앙에 오도록 만드는 우측 차선의 목표 X좌표입니다.
TARGET_CX = 480

# 주변 조명에 따라 하얀색 차선만 골라내기 위한 밝기 기준값입니다. (현장 상황에 따라 150~210 조절)
THRESH_VAL = 200

# ==============================================================================
# [2] 하드웨어 가변저항 조향 한계값 (아두이노 실측 데이터)
# ==============================================================================
STEER_CENTER = 157  # 직진 시 가변저항 값
STEER_LEFT = 210  # 좌회전 최대 꺾임 한계 (너무 크면 기구부 손상 주의)
STEER_RIGHT = 100  # 우회전 최대 꺾임 한계 (좌회전과 비율을 맞추기 위해 120 -> 100으로 확장)


def main():
    print("🚗 [1단계 전용] 카메라 및 가변저항 기반 정밀 차선 유지 주행 시작")

    # 하드웨어 통신 객체 생성
    ser_env = fl.libARDUINO()
    cam_env = fl.libCAMERA()

    # 아두이노 포트 연결 (장치 관리자에서 확인한 포트 번호로 설정)
    arduino_port = 'COM12'
    comm = ser_env.init(arduino_port, 9600)

    # 카메라 초기화 (0번 또는 1번 카메라 사용)
    ch0, _ = cam_env.initial_setting(cam0port=1, capnum=1)

    print("\n🚥 STAND BY: 차량을 트랙 정중앙에 정렬하고 키보드 's' 키를 눌러 출발하세요!\n")

    # ==============================================================================
    # [3] 출발 대기 루프
    # ==============================================================================
    # 's' 키를 누르기 전까지는 카메라마 켜두고 모터는 작동하지 않습니다.
    while True:
        _, frame0 = cam_env.camera_read(ch0)
        if frame0 is not None:
            # 대기 중임을 알리는 텍스트를 화면에 표시
            cv2.putText(frame0, "STAND BY - Press 's' to START", (50, 240), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 0, 255), 2)
            cv2.imshow("Track Camera", frame0)

        # 키보드 's' 키가 입력되면 대기 루프를 탈출하여 본격적인 주행을 시작합니다.
        if cv2.waitKey(1) & 0xFF == ord('s'):
            print("🚀 출발 신호 확인!")
            break

    # ==============================================================================
    # [4] 주행 상태 기억 변수 (루프 바깥에 선언하여 과거 데이터를 기억하게 함)
    # ==============================================================================
    # PD 제어(미분)를 위해 직전 프레임의 오차값을 저장할 변수
    prev_error = 0

    # 차선을 놓쳤을 때 서서히 핸들을 풀기 위해 직전 프레임의 조향각을 저장할 변수
    prev_target_angle = STEER_CENTER

    # ==============================================================================
    # [5] 메인 주행 제어 루프
    # ==============================================================================
    try:
        while True:
            # 1. 카메라 영상 읽기
            _, frame0 = cam_env.camera_read(ch0)

            if frame0 is not None:
                # 2. 이미지 전처리 (ROI 크롭 -> 흑백 변환 -> 블러 -> 이진화)
                roi = frame0[240:480, :]  # 화면의 아래쪽 절반(바닥)만 잘라내서 연산 속도 향상
                gray = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)
                blur = cv2.GaussianBlur(gray, (5, 5), 0)
                _, thresh = cv2.threshold(blur, THRESH_VAL, 255, cv2.THRESH_BINARY)

                h, w = thresh.shape  # 현재 크롭된 화면의 세로(h), 가로(w) 길이

                # ----------------------------------------------------------------------
                # 🌟 [핵심 기술 1] 동적 시야 가림 (Dynamic ROI)
                # ----------------------------------------------------------------------
                # 좌회전(175 이상)을 강하게 할 때는 우측 차선이 카메라 왼쪽으로 넘어오므로
                # 마스킹을 화면의 1/4(w/4)만 해서 차선을 끝까지 놓치지 않게 추적합니다.
                if prev_target_angle > 175:
                    thresh[:, 0:int(w / 4)] = 0
                    # 평소 직진이나 우회전을 할 때는 왼쪽 차선(노이즈)을 안 보도록 절반(w/2)을 완벽히 가립니다.
                else:
                    thresh[:, 0:int(w / 2)] = 0

                    # 3. 차선(하얀색 픽셀)의 무게중심점 산출
                M = cv2.moments(thresh)

                drive_dir = 1  # 구동 방향 (1: 전진)
                drive_speed = 0  # 속도 초기값

                # ----------------------------------------------------------------------
                # [상황 A] 카메라에 차선이 정상적으로 보일 때
                # ----------------------------------------------------------------------
                if M["m00"] > 0:
                    # 인식된 차선의 X좌표 중심점 연산
                    cx = int(M["m10"] / M["m00"])

                    # 목표점(480)과 현재 차선 위치(cx)의 픽셀 오차 계산
                    error = cx - TARGET_CX

                    # 🌟 [핵심 기술 2] PD 제어 파라미터 (지그재그 진동 억제)
                    Kp_steer = 0.5  # [비례] 오차에 따라 핸들을 꺾는 기본 힘
                    Kd_steer = 0.6  # [미분] 급격한 핸들링을 부드럽게 잡아주는 쇼바(댐퍼) 역할

                    base_speed = 130  # 직선 구간에서의 기본 주행 속도
                    Kd_speed = 0.8  # 코너 진입 시 오차에 비례하여 속도를 깎는 감속 민감도

                    # 미분값(오차의 변화량) 연산: (현재 오차 - 과거 오차)
                    derivative = error - prev_error

                    # 최종 조향 연산값 = (오차 * P가중치) + (오차변화량 * D가중치)
                    steer_val = (error * Kp_steer) + (derivative * Kd_steer)

                    # 센터값(157)을 기준으로 연산값을 빼서 최종 각도를 구함 (오차의 부호와 모터의 방향이 반대로 매칭)
                    target_angle = int(STEER_CENTER - steer_val)

                    # 계산된 각도가 물리적 조향 한계(100~210)를 넘지 않도록 제한
                    target_angle = max(STEER_RIGHT, min(target_angle, STEER_LEFT))

                    # 데드존(Deadzone) 설정: 오차가 8픽셀 이내면 미세한 떨림을 무시하고 직진 고정
                    if abs(error) <= 8:
                        target_angle = STEER_CENTER

                    # 코너 감속 제어: 오차가 클수록 최고 속도(base_speed)에서 속도를 빼고, 최저 60 유지
                    drive_speed = max(int(base_speed - (abs(error) * Kd_speed)), 60)

                    # 정상 상태이므로, 다음 루프의 미분 계산을 위해 현재 값을 '과거 변수'에 저장
                    prev_error = error
                    prev_target_angle = target_angle

                # ----------------------------------------------------------------------
                # [상황 B] S자 코너 등에서 차선이 시야 밖으로 일시적으로 사라졌을 때
                # ----------------------------------------------------------------------
                else:
                    # 🌟 [핵심 기술 3] 점진적 조향 복귀 (Decaying Memory)
                    # 차선을 놓치자마자 157(직진)로 확 풀어서 중앙선을 침범하거나,
                    # 과거 각도를 무한정 유지하여 벽에 충돌하는 현상을 동시에 방지합니다.

                    # 직전 핸들 각도의 85%를 유지하고 15%만 서서히 직진(센터)으로 풀어냅니다. (부드러운 복귀)
                    target_angle = int((prev_target_angle * 0.85) + (STEER_CENTER * 0.15))

                    # 앞이 안 보이므로 속도는 즉시 안전 속도(70)로 낮춤
                    drive_speed = 80

                    # 에러값 역시 확 0으로 만들지 않고 80%씩 부드럽게 감소시킴
                    prev_error = int(prev_error * 0.8)

                    # 갱신된 감쇠 각도를 다시 저장하여, 계속 안 보이면 결국 157로 천천히 수렴하게 됨
                    prev_target_angle = target_angle

                    print("⚠️ 차선 놓침 - 서서히 조향 복귀 중 (Decaying...)")

                # ----------------------------------------------------------------------
                # [6] 디버깅용 화면 시각화 정보 출력
                # ----------------------------------------------------------------------
                # 현재 마스킹(시야 가림막)이 어디까지 적용되었는지 파란색 세로선으로 표시
                mask_line = int(w / 4) if prev_target_angle > 175 else int(w / 2)
                cv2.line(roi, (mask_line, 0), (mask_line, 240), (255, 0, 0), 2)

                # 목표 중앙점(480) 위치를 초록색 세로선으로 표시
                cv2.line(roi, (TARGET_CX, 0), (TARGET_CX, 240), (0, 255, 0), 2)

                # 현재 인식된 차선의 무게중심(빨간점) 표시 (차선을 잃었을 땐 마지막 위치 근처에 표시)
                current_cx = TARGET_CX + error if M["m00"] > 0 else TARGET_CX + prev_error
                cv2.circle(roi, (current_cx, 120), 5, (0, 0, 255), -1)

                cv2.imshow("Advanced Lane Tracking (Stage 1)", roi)

                # ----------------------------------------------------------------------
                # [7] 아두이노로 주행 제어 명령 송신
                # ----------------------------------------------------------------------
                command = f"{drive_dir},{drive_speed},{target_angle}\n"
                comm.write(command.encode('utf-8'))

                print(f"[주행] 속도: {drive_speed:3d} | 목표각: {target_angle:3d}")

            # 키보드 'q'나 ESC 등 종료 신호가 들어오면 정지 명령 송신 후 루프 탈출
            if cam_env.loop_break():
                comm.write("0,0,164\n".encode('utf-8'))
                break

    # Ctrl+C 등 강제 종료가 발생했을 때 자동차가 폭주하는 것을 막는 안전장치
    except KeyboardInterrupt:
        comm.write("0,0,164\n".encode('utf-8'))

    # 프로그램이 종료될 때 메모리 누수 방지를 위해 카메라 창을 모두 닫음
    finally:
        cv2.destroyAllWindows()

if __name__ == "__main__":
    main()